"""Minimal Magic (.mag) layout library for the SKY130 analog neuron.

Devices are generated by Magic's PDK generators (magic::gencell) so their geometry is
PDK-correct; placement and routing are computed here and written as plain .mag text.

Units: the public API takes micrometres. .mag files use magscale 1 2 (1 unit = 5 nm), so every
coordinate must be a multiple of 5 nm; `u()` enforces that.

Routing style (see docs/layout.md):
  metal1  device terminals (generated)
  metal2  vertical risers from terminals to the routing channels
  metal3  horizontal tracks in the channels (one per net)
  metal4/5  power grid
"""
from __future__ import annotations

import os
import pathlib
import re
import shutil
import subprocess
from dataclasses import dataclass, field

ROOT = pathlib.Path(__file__).resolve().parents[2]
MAGDIR = ROOT / "mag" / "neuron"

# ---------------------------------------------------------------- units

def u(um: float) -> int:
    """micrometres -> .mag internal units (5 nm), exact."""
    v = round(um * 200)
    if abs(v - um * 200) > 1e-6:
        raise ValueError(f"{um} um is not on the 5 nm grid")
    return v


def snap(um: float) -> float:
    """Round micrometres to the 5 nm grid."""
    return round(um * 200) / 200


# Rule-derived sizes (um). See the via table in docs/layout.md.
VIA1 = 0.26          # via1 contact area (Magic contact incl. cut enclosure)
VIA1_PAD = 0.32      # metal1/metal2 pad around via1 (0.03 extra each side)
VIA2 = 0.28
VIA2_PAD_M2 = 0.37
VIA2_PAD_M3 = 0.50   # metal3 min area 0.24 um2
VIA3 = 0.32
VIA3_PAD = 0.50
M1_W, M2_W, M3_W, M4_W = 0.14, 0.14, 0.30, 0.30
RISER_W = 0.20       # metal2 riser width
TRACK_W = 0.30       # metal3 track width
TRACK_PITCH = 0.80   # metal3 track pitch (0.50 via pad + 0.30 space)

# ---------------------------------------------------------------- geometry

@dataclass(frozen=True)
class Rect:
    x1: float
    y1: float
    x2: float
    y2: float

    def __post_init__(self):
        if self.x2 < self.x1 or self.y2 < self.y1:
            raise ValueError(f"inverted rect {self}")

    @property
    def cx(self):
        return (self.x1 + self.x2) / 2

    @property
    def cy(self):
        return (self.y1 + self.y2) / 2

    @property
    def w(self):
        return self.x2 - self.x1

    @property
    def h(self):
        return self.y2 - self.y1

    def moved(self, dx, dy):
        return Rect(self.x1 + dx, self.y1 + dy, self.x2 + dx, self.y2 + dy)

    def grown(self, d):
        return Rect(self.x1 - d, self.y1 - d, self.x2 + d, self.y2 + d)

    def touches(self, o: "Rect"):
        return self.x1 <= o.x2 and o.x1 <= self.x2 and self.y1 <= o.y2 and o.y1 <= self.y2

    def contains(self, x, y):
        return self.x1 <= x <= self.x2 and self.y1 <= y <= self.y2


def bbox(rects):
    rects = list(rects)
    return Rect(min(r.x1 for r in rects), min(r.y1 for r in rects),
                max(r.x2 for r in rects), max(r.y2 for r in rects))


# Orientations as (a, b, d, e) of the Magic transform  x' = a x + b y + c,  y' = d x + e y + f
ORIENT = {"N": (1, 0, 0, 1), "FN": (-1, 0, 0, 1), "S": (-1, 0, 0, -1), "FS": (1, 0, 0, -1)}


def xform(r: Rect, orient: str, dx: float, dy: float) -> Rect:
    a, b, d, e = ORIENT[orient]
    xs = [a * x + b * y + dx for x, y in ((r.x1, r.y1), (r.x2, r.y2))]
    ys = [d * x + e * y + dy for x, y in ((r.x1, r.y1), (r.x2, r.y2))]
    return Rect(min(xs), min(ys), max(xs), max(ys))


# ---------------------------------------------------------------- .mag parsing

METAL1_TYPES = {"metal1", "viali", "mcon", "via1", "m2contact"}


def parse_mag(path: pathlib.Path):
    """Return (rects by layer in um, labels [(text, layer, x, y)], fixed_bbox or None)."""
    layers, labels, fixed = {}, [], None
    cur = None
    for line in path.read_text().splitlines():
        m = re.match(r"^<< (\S+) >>$", line)
        if m:
            cur = m.group(1)
            continue
        f = line.split()
        if cur and f and f[0] == "rect":
            x1, y1, x2, y2 = (int(v) / 200 for v in f[1:5])
            layers.setdefault(cur, []).append(Rect(x1, y1, x2, y2))
        elif cur == "labels" and f and f[0] == "rlabel":
            layer, x1, y1, x2, y2 = f[1], *(int(v) / 200 for v in f[2:6])
            labels.append((f[7], layer, (x1 + x2) / 2, (y1 + y2) / 2))
        elif cur == "labels" and f and f[0] == "flabel":
            layer, x1, y1, x2, y2 = f[1], *(int(v) / 200 for v in f[2:6])
            labels.append((f[-1], layer, (x1 + x2) / 2, (y1 + y2) / 2))
        elif f and f[0] == "string" and f[1] == "FIXED_BBOX":
            fixed = Rect(*(int(v) / 200 for v in f[2:6]))
    return layers, labels, fixed


def components(rects):
    """Group touching rectangles; return list of lists."""
    parent = list(range(len(rects)))

    def find(i):
        while parent[i] != i:
            parent[i] = parent[parent[i]]
            i = parent[i]
        return i

    for i in range(len(rects)):
        for j in range(i + 1, len(rects)):
            if rects[i].touches(rects[j]):
                parent[find(i)] = find(j)
    groups = {}
    for i in range(len(rects)):
        groups.setdefault(find(i), []).append(rects[i])
    return list(groups.values())


# ---------------------------------------------------------------- devices

@dataclass
class DevCell:
    """A generated device cell and its terminal geometry (cell coordinates, um)."""
    name: str
    bbox: Rect                    # FIXED_BBOX (abutment box)
    extent: Rect                  # all geometry
    pins: dict = field(default_factory=dict)   # terminal -> Rect (metal1 shape bbox)
    m1: list = field(default_factory=list)     # all metal1 shapes (bboxes) for checks


GEN_TYPES = {
    "nfet": "sky130_fd_pr__nfet_01v8",
    "pfet": "sky130_fd_pr__pfet_01v8",
    "rxh069": "sky130_fd_pr__res_xhigh_po_0p69",
    "rxh141": "sky130_fd_pr__res_xhigh_po_1p41",
    "mim": "sky130_fd_pr__cap_mim_m3_1",
}


def dev_name(kind, **p):
    parts = [kind] + [f"{k}{v}" for k, v in sorted(p.items())]
    return "_".join(parts).replace(".", "p")


def generate(specs, magdir=MAGDIR):
    """Generate device cells with Magic. specs: list of (kind, params dict).

    Cells are written to magdir under deterministic names (dev_name). Already-present cells
    are reused. Returns {name: DevCell}.
    """
    magdir.mkdir(parents=True, exist_ok=True)
    todo = [(k, p) for k, p in specs if not (magdir / f"{dev_name(k, **p)}.mag").exists()]
    if todo:
        tmp = ROOT / "build" / "layout" / "gen"
        shutil.rmtree(tmp, ignore_errors=True)
        tmp.mkdir(parents=True)
        tcl = ["snap internal", "load gentop -silent"]
        for i, (k, p) in enumerate(todo):
            args = " ".join(f"{a} {v}" for a, v in p.items())
            tcl += [f"box 0 {i * 20000} 0 {i * 20000}",
                    f"magic::gencell sky130::{GEN_TYPES[k]} g{i} {args}",
                    f'puts "GEN g{i} [instance list celldef g{i}]"']
        tcl += ["writeall force", "quit -noprompt"]
        (tmp / "gen.tcl").write_text("\n".join(tcl) + "\n")
        out = subprocess.run([str(ROOT / "scripts" / "magic_batch.sh"), str(tmp / "gen.tcl"), str(tmp)],
                             capture_output=True, text=True, env={**os.environ, "MAGIC_TIMEOUT": "300"})
        made = dict(re.findall(r"^GEN (g\d+) (\S+)$", out.stdout, re.M))
        for i, (k, p) in enumerate(todo):
            cell = made.get(f"g{i}")
            if not cell:
                raise RuntimeError(f"generation failed for {k} {p}:\n{out.stdout[-2000:]}")
            shutil.copy(tmp / f"{cell}.mag", magdir / f"{dev_name(k, **p)}.mag")
    return {dev_name(k, **p): load_dev(magdir / f"{dev_name(k, **p)}.mag") for k, p in specs}


def load_dev(path: pathlib.Path) -> DevCell:
    layers, labels, fixed = parse_mag(path)
    allr = [r for k, rs in layers.items() if k != "checkpaint" for r in rs]
    m1 = [r for t in METAL1_TYPES for r in layers.get(t, [])]
    comps = [bbox(c) for c in components(m1)]
    pins = {}
    for text, layer, x, y in labels:
        hits = [c for c in comps if c.contains(x, y)]
        if hits:
            pins[text] = hits[0]
    # metal3/metal4 terminals (MIM capacitor)
    for text, layer, x, y in labels:
        if text in pins:
            continue
        for t in ("metal4", "mimcapcontact", "via3", "metal3"):
            hits = [c for c in (bbox(g) for g in components(layers.get(t, []))) if c.contains(x, y)]
            if hits:
                pins[text] = hits[0]
                pins[text + ":layer"] = t
                break
    d = DevCell(path.stem, fixed or bbox(allr), bbox(allr), pins, comps)
    # guard-ring metal1 strips (components carrying no label) — e.g. "ringL", "ringR"
    labelled = set(map(id, pins.values()))
    free = [c for c in comps if not any(c is p for p in pins.values())]
    for c in free:
        if c.h > 4 * c.w:   # vertical strip
            side = "ringL" if c.cx < d.bbox.cx else "ringR"
            d.pins.setdefault(side, c)
        elif c.w > 4 * c.h:
            side = "ringB" if c.cy < d.bbox.cy else "ringT"
            d.pins.setdefault(side, c)
    return d


def load_macro(name, magdir=MAGDIR) -> DevCell:
    """A hierarchical cell written by Cell.write (e.g. ota5p, bias_ref) used as a macro.

    bbox = all paint plus child-instance boxes; pins = its port labels (metal3 points).
    """
    path = magdir / f"{name}.mag"
    layers, labels, _ = parse_mag(path)
    boxes = [r for k, rs in layers.items() if k != "checkpaint" for r in rs]
    tf = None
    for line in path.read_text().splitlines():
        f = line.split()
        if f and f[0] == "transform":
            tf = [int(v) for v in f[1:7]]
        elif f and f[0] == "box" and tf:
            a, b, c0, d, e, f0 = tf
            x1, y1, x2, y2 = (int(v) for v in f[1:5])
            xs = [a * x + b * y + c0 for x, y in ((x1, y1), (x2, y2))]
            ys = [d * x + e * y + f0 for x, y in ((x1, y1), (x2, y2))]
            boxes.append(Rect(min(xs) / 200, min(ys) / 200, max(xs) / 200, max(ys) / 200))
            tf = None
    ext = bbox(boxes)
    pins = {text: Rect(x - 0.1, y - 0.1, x + 0.1, y + 0.1) for text, layer, x, y in labels}
    return DevCell(name, ext, ext, pins, [])


# ---------------------------------------------------------------- layout cell

@dataclass
class Inst:
    dev: DevCell
    name: str
    orient: str
    dx: float
    dy: float

    def pin(self, t) -> Rect:
        return xform(self.dev.pins[t], self.orient, self.dx, self.dy)

    @property
    def box(self) -> Rect:
        return xform(self.dev.bbox, self.orient, self.dx, self.dy)

    @property
    def extent(self) -> Rect:
        return xform(self.dev.extent, self.orient, self.dx, self.dy)


class Cell:
    def __init__(self, name):
        self.name = name
        self.paint = {}           # layer -> [Rect]
        self.insts: list[Inst] = []
        self.labels = []          # (text, layer, Rect, port index, use)

    # --- placement
    def place(self, dev: DevCell, name: str, x: float, y: float, orient="N") -> Inst:
        """Place dev so that its bbox lower-left corner lands at (x, y)."""
        b = xform(dev.bbox, orient, 0, 0)
        inst = Inst(dev, name, orient, snap(x - b.x1), snap(y - b.y1))
        self.insts.append(inst)
        return inst

    # --- drawing
    def rect(self, layer, r: Rect):
        r = Rect(snap(r.x1), snap(r.y1), snap(r.x2), snap(r.y2))
        self.paint.setdefault(layer, []).append(r)
        return r

    def hwire(self, layer, x1, x2, y, w):
        return self.rect(layer, Rect(min(x1, x2), y - w / 2, max(x1, x2), y + w / 2))

    def vwire(self, layer, x, y1, y2, w):
        return self.rect(layer, Rect(x - w / 2, min(y1, y2), x + w / 2, max(y1, y2)))

    def via1(self, x, y):
        self.rect("metal1", Rect(x - VIA1_PAD / 2, y - VIA1_PAD / 2, x + VIA1_PAD / 2, y + VIA1_PAD / 2))
        self.rect("metal2", Rect(x - VIA1_PAD / 2, y - VIA1_PAD / 2, x + VIA1_PAD / 2, y + VIA1_PAD / 2))
        self.rect("via1", Rect(x - VIA1 / 2, y - VIA1 / 2, x + VIA1 / 2, y + VIA1 / 2))

    def via2(self, x, y):
        self.rect("metal2", Rect(x - VIA2_PAD_M2 / 2, y - VIA2_PAD_M2 / 2, x + VIA2_PAD_M2 / 2, y + VIA2_PAD_M2 / 2))
        self.rect("metal3", Rect(x - VIA2_PAD_M3 / 2, y - VIA2_PAD_M3 / 2, x + VIA2_PAD_M3 / 2, y + VIA2_PAD_M3 / 2))
        self.rect("via2", Rect(x - VIA2 / 2, y - VIA2 / 2, x + VIA2 / 2, y + VIA2 / 2))

    def via3(self, x, y):
        self.rect("metal3", Rect(x - VIA3_PAD / 2, y - VIA3_PAD / 2, x + VIA3_PAD / 2, y + VIA3_PAD / 2))
        self.rect("metal4", Rect(x - VIA3_PAD / 2, y - VIA3_PAD / 2, x + VIA3_PAD / 2, y + VIA3_PAD / 2))
        self.rect("via3", Rect(x - VIA3 / 2, y - VIA3 / 2, x + VIA3 / 2, y + VIA3 / 2))

    def label(self, text, layer, r: Rect, port, use="signal"):
        self.labels.append((text, layer, r, port, use))

    # --- output
    def write(self, magdir=MAGDIR):
        magdir.mkdir(parents=True, exist_ok=True)
        L = ["magic", "tech sky130A", "magscale 1 2", "timestamp 0"]
        for i in self.insts:
            a, b, d, e = ORIENT[i.orient]
            ext = i.dev.extent
            L += [f"use {i.dev.name}  {i.name}", "timestamp 0",
                  f"transform {a} {b} {u(i.dx)} {d} {e} {u(i.dy)}",
                  f"box {u(ext.x1)} {u(ext.y1)} {u(ext.x2)} {u(ext.y2)}"]
        for layer in sorted(self.paint):
            L.append(f"<< {layer} >>")
            for r in self.paint[layer]:
                L.append(f"rect {u(r.x1)} {u(r.y1)} {u(r.x2)} {u(r.y2)}")
        if self.labels:
            L.append("<< labels >>")
            for text, layer, r, port, use in self.labels:
                L.append(f"flabel {layer} {u(r.x1)} {u(r.y1)} {u(r.x2)} {u(r.y2)} 0 FreeSans 400 0 0 0 {text}")
                if port is not None:                 # None: net-name label only
                    L.append(f"port {port} nsew {use} bidirectional")
        L.append("<< end >>")
        (magdir / f"{self.name}.mag").write_text("\n".join(L) + "\n")
        return magdir / f"{self.name}.mag"

    def extent(self):
        rs = [i.extent for i in self.insts] + [r for rs in self.paint.values() for r in rs]
        return bbox(rs)
