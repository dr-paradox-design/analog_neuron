#!/usr/bin/env python3
"""Write a numeric LVS reference netlist from the simulation netlists.

netgen cannot evaluate parameter expressions ({7*ru}) or subcircuit-local .param lines, and it
reports parameters passed to subcircuit instances as unmatched properties. This script keeps the
subcircuit hierarchy but evaluates every expression with the values the design actually uses:
  - the top cell is evaluated with its default parameters;
  - each subcircuit instance's parameters are evaluated in the caller's scope; all instances of
    one subcircuit must resolve to the same values (true for this design), which then become the
    numeric body of that subcircuit, and the instance lines lose their parameters.

Usage: scripts/lvs_ref.py <top> <out.spice> <netlist.spice>...
"""
import math
import pathlib
import re
import sys

EXPR = re.compile(r"\{([^{}]*)\}")


def read_subckts(files):
    subs, order = {}, []
    for f in files:
        lines, cur = [], None
        for raw in pathlib.Path(f).read_text().splitlines():
            line = raw.split(";")[0].rstrip()
            if not line.strip() or line.lstrip().startswith("*"):
                continue
            if line.startswith("+") and lines:
                lines[-1] += " " + line[1:].strip()
            else:
                lines.append(line.strip())
        for line in lines:
            f0 = line.split()
            if f0[0].lower() == ".subckt":
                ports, defaults = [], {}
                for tok in f0[2:]:
                    if "=" in tok:
                        k, v = tok.split("=", 1)
                        defaults[k.lower()] = v
                    else:
                        ports.append(tok)
                cur = {"name": f0[1], "ports": ports, "defaults": defaults, "body": []}
            elif f0[0].lower() == ".ends":
                subs[cur["name"].lower()] = cur
                order.append(cur["name"].lower())
                cur = None
            elif cur is not None:
                cur["body"].append(line)
    return subs, order


def evaluate(val, scope):
    v = val.strip()
    if v.startswith("{") and v.endswith("}"):
        v = v[1:-1]
    try:
        return float(v)
    except ValueError:
        pass
    return float(eval(v, {"__builtins__": {}, "sqrt": math.sqrt}, dict(scope)))


def fmt(x):
    return f"{x:.6g}"


def resolve(subs, name, scope, resolved, done):
    """Evaluate subckt `name` with parameter scope; record child parameter sets."""
    s = subs[name]
    local = dict(scope)
    body = []
    for line in s["body"]:
        f = line.split()
        if f[0].lower() == ".param":
            for tok in re.findall(r"(\w+)\s*=\s*(\{[^}]*\}|\S+)", line[len(".param"):]):
                local[tok[0].lower()] = evaluate(tok[1], local)
            continue
        toks = line.split()
        model = next((t for t in toks[1:] if "=" not in t and t.lower() in subs), None)
        if toks[0][0].upper() == "X" and model is not None:
            child = subs[model.lower()]
            args = {k.lower(): v for k, v in (t.split("=", 1) for t in toks if "=" in t)}
            cscope = {k: evaluate(v, {}) if not v.startswith("{") else None
                      for k, v in child["defaults"].items()}
            for k, v in args.items():
                cscope[k] = evaluate(v, local)
            for k, v in child["defaults"].items():
                if cscope[k] is None:
                    cscope[k] = evaluate(v, cscope)
            prev = resolved.get(model.lower())
            if prev is not None and prev != cscope:
                raise SystemExit(f"{model}: instances resolve to different parameters "
                                 f"{prev} vs {cscope}; specialise by hand")
            resolved[model.lower()] = cscope
            resolve(subs, model.lower(), cscope, resolved, done)
            body.append(" ".join(t for t in toks if "=" not in t))
        else:
            body.append(EXPR.sub(lambda m: fmt(evaluate(m.group(1), local)), line))
    done[name] = body


def main():
    top, out, files = sys.argv[1].lower(), sys.argv[2], sys.argv[3:]
    subs, order = read_subckts(files)
    resolved, done = {}, {}
    scope = {k: evaluate(v, {}) for k, v in subs[top]["defaults"].items()}
    resolve(subs, top, scope, resolved, done)
    L = [f"* Numeric LVS reference for {top}, generated by scripts/lvs_ref.py from:",
         *[f"*   {f}" for f in files], "* Do not edit: regenerate instead.", ""]
    for name in order:
        if name not in done:
            continue
        s = subs[name]
        L.append(f".subckt {s['name']} {' '.join(s['ports'])}")
        L += done[name]
        L += [f".ends {s['name']}", ""]
    pathlib.Path(out).write_text("\n".join(L) + "\n")
    print(f"wrote {out}: " + ", ".join(f"{n} {resolved.get(n, 'top')}" for n in done))


if __name__ == "__main__":
    main()
